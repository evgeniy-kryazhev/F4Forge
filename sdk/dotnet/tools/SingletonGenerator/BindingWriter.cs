using System.Text;
using System.Text.Json;

namespace F4Forge.SingletonGenerator;

internal static class BindingWriter
{
    internal static void Write(BindingModel model, string root)
    {
        var managed = new StringBuilder("// <auto-generated />\n#nullable enable\nusing F4Forge.Net.Messaging;\n\nnamespace F4Forge.Net.Singletons;\n\n");
        var native = new StringBuilder("// Generated by SingletonGenerator. Do not edit.\n#include <RE/Fallout.h>\n");
        foreach (var header in model.Singletons.Select(singleton => singleton.Header).Distinct().Order(StringComparer.Ordinal))
        {
            native.AppendLine($"#include <{header}>");
        }
        native.AppendLine("\nnamespace f4forge::singletons {\n\nvoid RegisterGenerated(Bindings& bindings)\n{");
        foreach (var enumeration in model.Enums.Values)
        {
            managed.AppendLine($"/// <summary>Generated CommonLibF4 enumeration.</summary>\npublic enum {enumeration.Name} : {enumeration.UnderlyingType}\n{{");
            foreach (var (name, value) in enumeration.Values)
            {
                managed.AppendLine($"    /// <summary>Native value {value}.</summary>\n    @{name} = {value},");
            }
            managed.AppendLine("}\n");
        }
        foreach (var singleton in model.Singletons)
        {
            WriteSingleton(managed, native, singleton);
        }
        native.AppendLine("}\n\n}");
        WriteIfChanged(Path.Combine(root, "sdk/dotnet/F4Forge.Net/Singletons/Generated/Singletons.g.cs"), managed.ToString());
        WriteIfChanged(Path.Combine(root, "native/modules/singletons/generated.inc"), native.ToString());
        var report = JsonSerializer.Serialize(new
        {
            Singletons = model.Singletons.Select(singleton => new
            {
                singleton.Name,
                singleton.NativeName,
                singleton.Header,
                Members = singleton.Members.Select(member => new { member.Name, member.Route })
            }),
            Skipped = model.Skipped.Order(StringComparer.Ordinal)
        }, new JsonSerializerOptions { WriteIndented = true });
        WriteIfChanged(Path.Combine(root, "sdk/dotnet/tools/SingletonGenerator/bindings-report.json"), report + "\n");
    }

    private static void WriteSingleton(StringBuilder managed, StringBuilder native, Singleton singleton)
    {
        managed.AppendLine($"/// <summary>Borrowed engine singleton proxy for {singleton.NativeName}. Members require the game thread.</summary>");
        managed.AppendLine($"public sealed class {singleton.Name} : IGameSingleton<{singleton.Name}>\n{{");
        managed.AppendLine("    private readonly IMessageChannel _messages;\n");
        managed.AppendLine($"    private {singleton.Name}(IMessageChannel messages)\n    {{\n        _messages = messages;\n    }}\n");
        managed.AppendLine($"    static {singleton.Name} IGameSingleton<{singleton.Name}>.Create(IMessageChannel messages)\n    {{\n        return new {singleton.Name}(messages);\n    }}\n");
        managed.AppendLine("    /// <summary>Checks whether the engine singleton is currently available. Requires the game thread.</summary>");
        var availability = $"singletons.{singleton.NativeName}.available";
        managed.AppendLine($"    public bool IsAvailable => _messages.Call<bool>(\"{availability}\", null);\n");
        var pointer = singleton.ReturnsPointer ? "" : "std::addressof";
        var getter = singleton.ReturnsPointer ? $"{singleton.NativeName}::GetSingleton()" : $"{pointer}({singleton.NativeName}::GetSingleton())";
        native.AppendLine($"    bindings.Add(\"{availability}\", [](const DataValue&) {{\n        return {getter} != nullptr;\n    }});");
        foreach (var member in singleton.Members)
        {
            managed.AppendLine($"    /// <summary>Calls {singleton.NativeName}::{member.NativeName} on the game thread.</summary>");
            var callType = member.Result.Managed == "void" ? "bool" : member.Result.Managed;
            var payload = member.Parameters.Count == 0 ? "null" : "new { " + string.Join(", ", member.Parameters.Select(parameter => "@" + parameter.Name)) + " }";
            if (member.IsField)
            {
                managed.AppendLine($"    public {member.Result.Managed} @{member.Name} => _messages.Call<{callType}>(\"{member.Route}\", null);\n");
            }
            else
            {
                foreach (var parameter in member.Parameters)
                {
                    managed.AppendLine($"    /// <param name=\"{parameter.Name}\">Copied native argument.</param>");
                }
                var parameters = string.Join(", ", member.Parameters.Select(parameter => $"{parameter.Type.Managed} @{parameter.Name}"));
                managed.AppendLine($"    public {member.Result.Managed} @{member.Name}({parameters})\n    {{");
                foreach (var parameter in member.Parameters.Where(parameter => parameter.Type.IsString))
                {
                    managed.AppendLine($"        ArgumentNullException.ThrowIfNull(@{parameter.Name});");
                    managed.AppendLine($"        if (@{parameter.Name}.Contains('\\0'))\n        {{\n            throw new ArgumentException(\"Native strings cannot contain NUL characters.\", nameof(@{parameter.Name}));\n        }}");
                }
                var returnPrefix = member.Result.Managed == "void" ? "" : "return ";
                managed.AppendLine($"        {returnPrefix}_messages.Call<{callType}>(\"{member.Route}\", {payload});\n    }}\n");
            }
            var argumentsName = member.Parameters.Count == 0 ? "" : " arguments";
            native.AppendLine($"    bindings.Add(\"{member.Route}\", [](const DataValue&{argumentsName}) -> DataValue {{");
            native.AppendLine($"        auto* singleton = RequireSingleton({getter}, \"{singleton.NativeName}\");");
            foreach (var parameter in member.Parameters)
            {
                var type = parameter.Type;
                var storage = type.IsString ? "std::string" : type.Native;
                native.AppendLine($"        const auto {parameter.Name}Value = ReadArgument<{storage}>(arguments.at(\"{parameter.Name}\"));");
            }
            var invocationArguments = string.Join(", ", member.Parameters.Select(parameter => parameter.Type.IsString
                ? $"RE::BSFixedString({parameter.Name}Value.c_str())"
                : $"static_cast<{parameter.Type.ArgumentCast ?? parameter.Type.Native}>({parameter.Name}Value)"));
            var invocation = member.IsField ? $"singleton->{member.NativeName}" : $"singleton->{member.NativeName}({invocationArguments})";
            if (member.Result.Managed == "void")
            {
                native.AppendLine($"        {invocation};\n        return true;");
            }
            else if (member.Result.IsString)
            {
                native.AppendLine($"        const auto result = {invocation};\n        const auto* text = result.c_str();\n        return text != nullptr ? std::string(text) : std::string{{}};");
            }
            else if (member.Result.IsEnum)
            {
                native.AppendLine($"        return static_cast<std::underlying_type_t<{member.Result.Native}>>({invocation});");
            }
            else
            {
                native.AppendLine($"        return static_cast<{member.Result.Native}>({invocation});");
            }
            native.AppendLine("    });");
        }
        managed.AppendLine("}\n");
    }

    private static void WriteIfChanged(string path, string content)
    {
        content = content.Replace("\r\n", "\n").TrimEnd('\n') + "\n";
        if (File.Exists(path) && File.ReadAllText(path) == content)
        {
            return;
        }
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content, new UTF8Encoding(false));
    }
}
