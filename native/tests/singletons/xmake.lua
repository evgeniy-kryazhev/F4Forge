set_xmakever("3.1.0")
set_project("F4Forge.Singletons.Tests")
set_languages("c++23")
set_arch("x64")
set_runtimes("MT")
add_rules("mode.debug", "mode.releasedbg")
add_requires("nlohmann_json 3.12.0")

local root = path.absolute("../../..", os.scriptdir())

target("F4Forge.Singletons.Tests")
    set_kind("binary")
    set_targetdir(path.join(root, "build/tests"))
    add_packages("nlohmann_json")
    add_includedirs("fixtures", path.join(root, "build/singletons/fixture/native/modules/singletons"))
    add_includedirs(path.join(root, "native/core"), path.join(root, "native/modules/singletons"))
    add_cxxflags("/W4", "/WX", "/permissive-", "/EHsc", "/utf-8")
    add_files(path.join(root, "native/core/**.cpp"))
    add_files(path.join(root, "native/modules/singletons/bindings.cpp"))
    add_files("main.cpp")
    before_build(function()
        os.vrunv("dotnet", {"run", "--project", path.join(root, "sdk/dotnet/tools/SingletonGenerator"),
            "-c", "Release", "--", root, "--self-test"})
    end)
